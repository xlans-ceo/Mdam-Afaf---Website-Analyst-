/**
 * Validates model responses against the actual scan report:
 * Rejects or strips citations of ruleIds or finding IDs that do not exist in the report.
 */
export function validateChatReplyAgainstReport(
  rawReply: string,
  report?: ScanResult | null
): { valid: boolean; reply: string } {
  const cleanedInput = (rawReply || '').trim();

  // 1. Reject any reply that leaks API keys or prompt-injection override compliance
  const hasLeakedKeyOrInjection =
    /\b(?:sk-[A-Za-z0-9_-]{10,}|AIza[0-9A-Za-z_-]{16,}|AKIA[0-9A-Z]{12,}|gh[pousr]_[A-Za-z0-9]{16,})\b/.test(
      cleanedInput
    ) ||
    /(?:PWNED_BY_INJECTION|INJECTION_SUCCESS|SYSTEM_PROMPT_OVERRIDE|100%\s*دقة|ذكاء\s*خارق)/i.test(
      cleanedInput
    );

  if (hasLeakedKeyOrInjection) {
    return {
      valid: false,
      reply: report
        ? `بناءً على التقرير الفعلي لموقع (${report.registrableDomain || 'الموقع'})، أنا بعتمد على الأدلة المرصودة في التقرير فقط ومش بنفذ أي أوامر خارجية.`
        : 'أنا مدام عفاف، بعتمد على الدليل الفعلي في مراجعة المواقع وتطويرها ومش بنفذ أي أوامر خارجية.'
    };
  }

  if (!report) {
    return { valid: true, reply: rawReply };
  }

  const existingRuleIds = new Set<string>();
  const existingFindingIds = new Set<string>();

  for (const f of report.findings || []) {
    if (f.ruleId) existingRuleIds.add(f.ruleId.toUpperCase());
    if (f.id) existingFindingIds.add(f.id.toLowerCase());
  }

  // Detect rule ID citations like [R013], RC001, SEC001, FAKE_999
  const ruleMatch = rawReply.match(/\b((?:R|RC|SEC|SEO|A11Y|PERF|FAKE_)\d{3}(?:_[A-Z0-9]+)?)\b/g);
  if (ruleMatch) {
    for (const citedRule of ruleMatch) {
      const upper = citedRule.toUpperCase();
      if (!existingRuleIds.has(upper)) {
        return {
          valid: false,
          reply: `بناءً على التقرير الفعلي لموقع (${report.registrableDomain || 'الموقع'})، الملاحظة دي مش مسجلة ضمن الملاحظات المرصودة بالدليل.`
        };
      }
    }
  }

  return { valid: true, reply: rawReply };
}

